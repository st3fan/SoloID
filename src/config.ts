import { readFile } from 'node:fs/promises';
import { createPrivateKey, createPublicKey, hkdfSync, randomBytes } from 'node:crypto';
import { calculateJwkThumbprint, exportJWK, importJWK, type JWK, type CryptoKey } from 'jose';
import { z } from 'zod';
import { hashPassword, hashPattern } from './password.js';

export const normalizeEmail = (email: string) => email.trim().toLowerCase();
const httpURL = z.string().max(2048).refine((value) => {
  try {
    const u = new URL(value);
    return !u.username && !u.password && !value.includes('#') && !value.includes('*') &&
      (u.protocol === 'https:' || (u.protocol === 'http:' && u.hostname === 'localhost'));
  } catch { return false; }
}, 'Use an exact HTTPS URL without credentials or fragment (HTTP localhost is allowed)');
const identifier = z.string().regex(/^[A-Za-z0-9_-]{1,128}$/);
const passwordHash = z.string().regex(hashPattern, 'Use a hash generated by soloid hash');
const email = z.string().trim().toLowerCase().pipe(z.email().max(254));
const userSchema = z.object({
  id: identifier,
  email,
  name: z.string().min(1).max(200).optional(),
  email_verified: z.boolean().default(false),
  password_hash: passwordHash,
}).strict();
const clientSchema = z.object({
  client_id: identifier,
  name: z.string().min(1).max(100).optional(),
  public: z.boolean().default(false),
  client_secret_hash: passwordHash.optional(),
  redirect_uris: z.array(httpURL).min(1).max(20),
  post_logout_redirect_uris: z.array(httpURL).max(20).default([]),
  allowed_users: z.array(identifier).optional(),
}).strict().refine(c => c.public ? !c.client_secret_hash : !!c.client_secret_hash,
  'Public clients must have no secret; confidential clients must have a secret hash');
const schema = z.object({
  issuer: httpURL.refine(value => {
    const u = new URL(value);
    return u.pathname === '/' && !u.search && value === u.origin;
  }, 'Issuer must be an origin with no path, query, or trailing slash'),
  secret: z.string().regex(/^[A-Za-z0-9_-]{43}$/),
  signing_key: z.record(z.string(), z.unknown()),
  previous_public_keys: z.array(z.record(z.string(), z.unknown())).max(5).default([]),
  session_ttl: z.string().regex(/^[1-9][0-9]*(m|h|d)$/).default('12h'),
  users: z.array(userSchema).min(1).max(1000),
  clients: z.array(clientSchema).min(1).max(100),
}).strict();

export type User = z.infer<typeof userSchema>;
export type Client = z.infer<typeof clientSchema>;
export type Config = z.infer<typeof schema>;
export type Runtime = {
  config: Config;
  users: Map<string, User>;
  clients: Map<string, Client>;
  sessionSeconds: number;
  cookieKey: Uint8Array;
  signingKey: CryptoKey;
  jwks: { keys: JWK[] };
  kid: string;
  dummyHash: string;
};

export async function prepareConfig(input: unknown): Promise<Runtime> {
  const config = schema.parse(input);
  const unique = (values: string[], label: string) => {
    if (new Set(values).size !== values.length) throw new Error(`Duplicate ${label}`);
  };
  unique(config.users.map(u => u.id), 'user ID');
  unique(config.users.map(u => u.email), 'email');
  unique(config.clients.map(c => c.client_id), 'client ID');
  for (const c of config.clients) {
    if (c.allowed_users?.some(id => !config.users.some(u => u.id === id))) {
      throw new Error('allowed_users must reference configured user IDs');
    }
  }
  const sessionSeconds = Number.parseInt(config.session_ttl) *
    ({ m: 60, h: 3600, d: 86400 }[config.session_ttl.slice(-1)]!);
  if (!Number.isSafeInteger(sessionSeconds) || sessionSeconds > 30 * 86400) {
    throw new Error('session_ttl must be at most 30 days');
  }
  const secret = Buffer.from(config.secret, 'base64url');
  if (secret.length !== 32 || secret.toString('base64url') !== config.secret) throw new Error('Invalid secret');
  const jwk = config.signing_key as JWK;
  if (jwk.kty !== 'RSA' || !jwk.d || !jwk.p || !jwk.q || !jwk.dp || !jwk.dq || !jwk.qi) {
    throw new Error('signing_key must be a complete RSA private JWK');
  }
  const privateKey = createPrivateKey({ key: jwk, format: 'jwk' });
  if ((privateKey.asymmetricKeyDetails?.modulusLength ?? 0) < 2048) throw new Error('RSA key must be at least 2048 bits');
  const pub = await exportJWK(createPublicKey(privateKey));
  const kid = await calculateJwkThumbprint(pub);
  const keys: JWK[] = [{ ...pub, kid, use: 'sig', alg: 'RS256' }];
  for (const raw of config.previous_public_keys) {
    if (['d', 'p', 'q', 'dp', 'dq', 'qi', 'k'].some(k => k in raw) || raw.kty !== 'RSA') {
      throw new Error('previous_public_keys must contain only public RSA keys');
    }
    const key = createPublicKey({ key: raw, format: 'jwk' });
    if ((key.asymmetricKeyDetails?.modulusLength ?? 0) < 2048) throw new Error('RSA key must be at least 2048 bits');
    const clean = await exportJWK(key);
    keys.push({ ...clean, kid: await calculateJwkThumbprint(clean), use: 'sig', alg: 'RS256' });
  }
  unique(keys.map(k => k.kid!), 'signing key');
  return {
    config, users: new Map(config.users.map(u => [u.id, u])),
    clients: new Map(config.clients.map(c => [c.client_id, c])), sessionSeconds,
    cookieKey: new Uint8Array(hkdfSync('sha256', secret, '', 'soloid:cookie:v1', 32)),
    signingKey: await importJWK({ ...jwk, alg: 'RS256' }, 'RS256') as CryptoKey,
    jwks: { keys }, kid, dummyHash: await hashPassword(randomBytes(32).toString('base64url')),
  };
}

export async function loadConfig(path: string) {
  return prepareConfig(JSON.parse(await readFile(path, 'utf8')));
}

export function allowed(client: Client, user: User) {
  return !client.allowed_users || client.allowed_users.includes(user.id);
}
