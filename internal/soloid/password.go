package soloid

import (
	"crypto/rand"
	"crypto/subtle"
	"encoding/base64"
	"errors"
	"strings"

	"golang.org/x/crypto/argon2"
)

var ErrBusy = errors.New("temporarily unavailable")
var passwordSlots = make(chan struct{}, 2)

const hashPrefix = "$argon2id$v=19$m=65536,t=3,p=4$"

func HashPassword(password string) string {
	salt := make([]byte, 16)
	if _, err := rand.Read(salt); err != nil {
		panic(err)
	}
	key := argon2.IDKey([]byte(password), salt, 3, 65536, 4, 32)
	return hashPrefix + base64.RawStdEncoding.EncodeToString(salt) + "$" + base64.RawStdEncoding.EncodeToString(key)
}

func parseHash(encoded string) (salt, key []byte, err error) {
	if !strings.HasPrefix(encoded, hashPrefix) {
		return nil, nil, errors.New("use a hash generated by soloid hash")
	}
	parts := strings.Split(strings.TrimPrefix(encoded, hashPrefix), "$")
	if len(parts) != 2 {
		return nil, nil, errors.New("invalid password hash")
	}
	salt, err = base64.RawStdEncoding.Strict().DecodeString(parts[0])
	if err != nil || len(salt) != 16 || base64.RawStdEncoding.EncodeToString(salt) != parts[0] {
		return nil, nil, errors.New("invalid hash salt")
	}
	key, err = base64.RawStdEncoding.Strict().DecodeString(parts[1])
	if err != nil || len(key) != 32 || base64.RawStdEncoding.EncodeToString(key) != parts[1] {
		return nil, nil, errors.New("invalid hash output")
	}
	return salt, key, nil
}

func verifyPassword(encoded, password string) (bool, error) {
	select {
	case passwordSlots <- struct{}{}:
	default:
		return false, ErrBusy
	}
	defer func() { <-passwordSlots }()
	salt, expected, err := parseHash(encoded)
	if err != nil {
		return false, err
	}
	actual := argon2.IDKey([]byte(password), salt, 3, 65536, 4, 32)
	return subtle.ConstantTimeCompare(actual, expected) == 1, nil
}
